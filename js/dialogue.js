const lastIdx = {};
function pick(id, key, arr) {
  const k = id + key;
  let i = Math.floor(Math.random() * arr.length);
  if (arr.length > 1 && i === lastIdx[k]) i = (i + 1) % arr.length;
  lastIdx[k] = i;
  return arr[i];
}
