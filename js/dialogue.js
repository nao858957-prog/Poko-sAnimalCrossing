function callName(cid, lv, n) {
  if (cid === 'sei' || cid === 'kuro' || cid === 'pon') return n + 'さん';
  if (cid === 'mei') return lv <= 0 ? 'あなた' : lv === 1 ? n + 'さん' : n;
  if (cid === 'poko' || cid === 'rin') return n + (lv < 2 ? 'さん' : 'ちゃん');
  return lv < 2 ? n + 'さん' : n;
}
