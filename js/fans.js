const clean = s => s.normalize('NFKC').toLowerCase().replace(/\s|[ー〜~・.]/g, '');
export function fanOf(name) {
  const n = clean(name || '');
  if (n.length < 2) return null;
  return FANS.find(f => f.k.some(k => { const c = clean(k); return n.includes(c) || (n.length >= 3 && c.includes(n)); })) || null;
}
// そのひとへの ひとこと
export function fanLine(fan, cid, name) {
  const t = fan[cid] || OTHER[cid];
  return t ? t.replace(/\{n\}/g, name.replace(/(さん|ちゃん|くん|君|たん)$/, '')) : null;
}

