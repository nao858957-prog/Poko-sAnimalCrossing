const dstr = d => `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
const nameOf = n => (n || '').replace(/(さん|ちゃん|くん|君|たん)$/, '');
const fillN = (t, name) => t.replace(/\{n\}/g, nameOf(name));
const newsActive = (now = new Date()) => NEWS.filter(n => dstr(now) >= n.from && dstr(now) <= n.to);
// きょうの あいさつの もと: さいきんの できごと (まだ はなしてない) → なければ ふだんの ひとこと(まいかい ちがう もの)
export function fanGreeting(fan, cid, name, mem) {
  mem.news = mem.news || {}; mem.idx = mem.idx || {};
  for (const n of mem.idx[cid] ? newsActive() : []) {   // はじめての あいさつは その ひとだけの ひとこと。2かいめから さいきんの できごとを まぜる
    const t = n.who && n.who[cid];
    if (t && !mem.news[n.id + ':' + cid]) { mem.news[n.id + ':' + cid] = 1; return fillN(t, name); }
  }
  const pool = [fan[cid] || OTHER[cid], ...((fan.more && fan.more[cid]) || [])].filter(Boolean);
  if (!pool.length) return null;
  const i = mem.idx[cid] || 0; mem.idx[cid] = i + 1;
  return fillN(pool[i % pool.length], name);
}
// ことばに はんのうする おはなし。(1) その ひとだけの topics (2)「さいきん どう？」→ さいきんの できごと
export function fanTopic(fan, cid, text, name) {
  const t = clean(text || '');
  if (!fan || t.length < 2) return null;
  for (const tp of fan.topics || []) if (tp.who[cid] && tp.k.some(k => t.includes(clean(k)))) return fillN(tp.who[cid], name);
  for (const n of newsActive()) if (n.who && n.who[cid] && (n.key || []).some(k => t.includes(clean(k)))) return fillN(n.who[cid], name);
  return null;
}
