// きょうの あいさつの もと: さいきんの できごと (まだ はなしてない) → なければ ふだんの ひとこと(まいかい ちがう もの)
export function fanGreeting(fan, cid, name, mem) {
  mem.news = mem.news || {}; mem.idx = mem.idx || {};
  for (const n of mem.idx[cid] ? newsActive() : []) {   // はじめての あいさつは その ひとだけの ひとこと。2かいめから さいきんの できごとを まぜる
    const t = n.who && n.who[cid];
    if (t && !mem.news[n.id + ':' + cid]) { mem.news[n.id + ':' + cid] = 1; return { text: fillN(t, name), vid: n.vid || null }; }
  }
  const pool = [fan[cid] || OTHER[cid], ...((fan.more && fan.more[cid]) || [])].filter(Boolean);
  if (!pool.length) return null;
  const i = mem.idx[cid] || 0; mem.idx[cid] = i + 1;
  return { text: fillN(pool[i % pool.length], name), vid: null };
}
// ことばに はんのうする おはなし。(1) その ひとだけの topics (2) どうがの なかみ (3)「さいきん どう？」→ どれかの どうが
export function fanTopic(fan, cid, text, name) {
  const t = clean(text || '');
  if (!fan || t.length < 2) return null;
  for (const tp of fan.topics || []) if (tp.who[cid] && tp.k.some(k => t.includes(clean(k)))) return { text: fillN(tp.who[cid], name), vid: null };
  const act = newsActive().filter(n => n.who && n.who[cid]);
  let best = null, bl = 0;
  for (const n of act) for (const k of n.key || []) { const c = clean(k); if (t.includes(c) && c.length > bl) { best = n; bl = c.length; } }
  if (best) return { text: fillN(best.who[cid], name), vid: best.vid || null };
  if (act.length && NEWS_ANY.some(k => t.includes(clean(k)))) { const n = act[Math.floor(Math.random() * act.length)]; return { text: fillN(n.who[cid], name), vid: n.vid || null }; }
  return null;
}
